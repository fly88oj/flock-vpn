//! Admin loopback endpoint (the operations surface of the process entry in
//! docs/design.md §3.11).
//!
//! The **in-process single-writer entry point** for NetState write operations
//! such as invite minting/redemption/device registration/revocation: redb is
//! written exclusively by the server process; CLI subcommands
//! (`invite`/`redeem`/`device-add`/`revoke`) enter through this TCP endpoint
//! (the 127.0.0.1 bind = the authentication boundary; the container form
//! does not map it to the host —— `docker compose exec` goes over the
//! container network). Since M4 these operations migrate into Raft admin
//! operations (§3.10 admin_op, requiring a cluster root-key signature).

use serde::{Deserialize, Serialize};
use tokio::io::{AsyncRead, AsyncReadExt, AsyncWrite, AsyncWriteExt};
use tokio::net::{TcpListener, TcpStream};
use tokio::task::JoinHandle;

use crate::control::DevicePubs;
use crate::netstate::RedeemRequest;
use crate::server::ServerCore;

/// Single admin message size cap.
const MAX_ADMIN_MSG: usize = 256 * 1024;

async fn send_msg<S: AsyncWrite + Unpin, M: Serialize>(io: &mut S, msg: &M) -> std::io::Result<()> {
    let bytes = postcard::to_allocvec(msg).map_err(|e| std::io::Error::other(e.to_string()))?;
    if bytes.len() > MAX_ADMIN_MSG {
        return Err(std::io::Error::other("admin msg too large"));
    }
    io.write_all(&(bytes.len() as u32).to_le_bytes()).await?;
    io.write_all(&bytes).await?;
    io.flush().await
}

async fn recv_msg<S: AsyncRead + Unpin, M: for<'de> Deserialize<'de>>(
    io: &mut S,
) -> std::io::Result<M> {
    let mut hdr = [0u8; 4];
    io.read_exact(&mut hdr).await?;
    let len = u32::from_le_bytes(hdr) as usize;
    if len == 0 || len > MAX_ADMIN_MSG {
        return Err(std::io::Error::other("admin frame length"));
    }
    let mut buf = vec![0u8; len];
    io.read_exact(&mut buf).await?;
    postcard::from_bytes(&buf).map_err(|e| std::io::Error::other(e.to_string()))
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum AdminRequest {
    /// Mint an invite (returns the full v3 invite file as b64).
    Invite { ttl_secs: u64 },
    /// Redeem an invite (the account-creation path when no session exists:
    /// admin-operation semantics, §1.3.3f).
    Redeem {
        invite_b64: String,
        username: String,
        device: DevicePubs,
    },
    /// Register a device directly (the server-side pre-provisioning of the
    /// TOFU flow; an admin operation).
    DeviceAdd {
        username: String,
        device: DevicePubs,
    },
    /// Revoke a device (advances the epoch + kills local sessions).
    Revoke { device: [u8; 32] },
    /// Runtime status snapshot (the M5 assertion surface: epoch/leader/
    /// forwarding counters/online sessions —— the `stats` subcommand).
    Stats,
    /// Multi-primary write pass-through (feature `multi-primary`):
    /// root-signed admin operations (Bootstrap/SetOprf/RecordInvite ——
    /// signature verification happens inside the Raft state machine; admin
    /// only passes through).
    #[cfg(feature = "multi-primary")]
    SignedWrite { req: flock_sync::proto::SyncRequest },
    /// M8 (§7-M8.3): the server half of `web-admin-add` —— OPAQUE
    /// registration m1 → m2 (the loopback bind = the authentication boundary,
    /// same trust level as the existing invite/revoke). The target user
    /// already having a password ⇒ Err with guidance to use the Web reset.
    WebPwBegin { user: String, m1_b64: String },
    /// M8: the registration commit tail (CreateUser (UserExists ignored
    /// idempotently) + SetPasswordBootstrap + SetUserAdmin; the token is
    /// generated by the CLI and carried in the message —— reusing the five
    /// Raft write semantics).
    WebPwCommit {
        user: String,
        token: [u8; 16],
        record_b64: String,
        profile: u16,
        admin: bool,
    },
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum AdminResponse {
    Invite {
        invite_b64: String,
    },
    Redeemed {
        device_id: [u8; 32],
        vip: [u8; 4],
    },
    DeviceAdded {
        device_id: [u8; 32],
        vip: [u8; 4],
    },
    Revoked {
        epoch: u64,
    },
    /// Line-oriented key/value pairs for Stats (one `key=value` per line; the
    /// script-grep surface).
    StatsText {
        lines: Vec<String>,
    },
    /// Receipt of SignedWrite (Debug text form —— a readable rendering of
    /// `Ok`/`Error(..)`).
    WriteReceipt {
        text: String,
    },
    /// M8: the m2 of WebPwBegin (the second OPAQUE registration step).
    WebPwM2 {
        m2_b64: String,
    },
    /// M8: the receipt of WebPwCommit.
    WebPwDone {
        username: String,
    },
    Err {
        msg: String,
    },
}

fn b64_encode(b: &[u8]) -> String {
    use base64::Engine as _;
    base64::engine::general_purpose::STANDARD_NO_PAD.encode(b)
}

fn b64_decode(s: &str) -> Result<Vec<u8>, String> {
    use base64::Engine as _;
    let t = s.trim();
    base64::engine::general_purpose::STANDARD_NO_PAD
        .decode(t)
        .or_else(|_| base64::engine::general_purpose::STANDARD.decode(t))
        .map_err(|e| format!("b64: {e}"))
}

/// Start the admin endpoint (returns the task handle; a bind failure is
/// Err).
pub async fn serve(
    core: std::sync::Arc<ServerCore>,
    bind: std::net::SocketAddr,
) -> std::io::Result<JoinHandle<()>> {
    let listener = TcpListener::bind(bind).await?;
    Ok(tokio::spawn(async move {
        loop {
            let Ok((mut io, _)) = listener.accept().await else {
                return;
            };
            let core = core.clone();
            tokio::spawn(async move {
                let _ = handle_conn(&core, &mut io).await;
            });
        }
    }))
}

async fn handle_conn(core: &ServerCore, io: &mut TcpStream) -> std::io::Result<()> {
    let req: AdminRequest = recv_msg(io).await?;
    let resp = dispatch(core, req).await;
    send_msg(io, &resp).await
}

async fn dispatch(core: &ServerCore, req: AdminRequest) -> AdminResponse {
    let net = &core.net;
    match req {
        AdminRequest::Invite { ttl_secs } => match core.mint_invite(ttl_secs).await {
            Ok(bytes) => AdminResponse::Invite {
                invite_b64: b64_encode(&bytes),
            },
            Err(e) => AdminResponse::Err { msg: e },
        },
        AdminRequest::Redeem {
            invite_b64,
            username,
            device,
        } => {
            let invite = match b64_decode(&invite_b64) {
                Ok(v) => v,
                Err(e) => return AdminResponse::Err { msg: e },
            };
            match net
                .redeem_invite(RedeemRequest {
                    invite_bytes: &invite,
                    username: &username,
                    device_x25519: device.x25519,
                    device_ed25519: device.ed25519,
                    hostname: &device.hostname,
                    expected_root_pub: *core.identity.root_pub.as_bytes(),
                    expected_cluster_id: core.identity.cluster_id.0,
                    now_unix: flock_protocol::trust::now_unix(),
                })
                .await
            {
                Ok(out) => AdminResponse::Redeemed {
                    device_id: out.device_id,
                    vip: out.vip,
                },
                Err(e) => AdminResponse::Err { msg: e.to_string() },
            }
        }
        AdminRequest::DeviceAdd { username, device } => {
            match net
                .register_device(&username, device.x25519, device.ed25519, &device.hostname)
                .await
            {
                Ok(row) => AdminResponse::DeviceAdded {
                    device_id: flock_protocol::session::DeviceId(
                        *flock_protocol::ed25519_dalek::VerifyingKey::from_bytes(&device.ed25519)
                            .expect("32B ed25519")
                            .as_bytes(),
                    )
                    .0,
                    vip: row.vip,
                },
                Err(e) => AdminResponse::Err { msg: e.to_string() },
            }
        }
        AdminRequest::Revoke { device } => {
            let id = flock_protocol::session::DeviceId(device);
            match net.revoke(&id).await {
                Ok(epoch) => {
                    core.sessions.kill(&device);
                    AdminResponse::Revoked { epoch }
                }
                Err(e) => AdminResponse::Err { msg: e.to_string() },
            }
        }
        AdminRequest::Stats => AdminResponse::StatsText {
            lines: stats_lines(core).await,
        },
        AdminRequest::WebPwBegin { user, m1_b64 } => {
            // Password already set ⇒ reject with guidance (the CLI side
            // checks the same; this is the backstop).
            if net
                .user_row(&user)
                .await
                .is_some_and(|r| r.opaque_record.is_some())
            {
                return AdminResponse::Err {
                    msg: format!(
                        "user {user} already has a password - web-admin-add is for first-time setup only; reset existing passwords via the Web UI (admin /api/users/{user}/reset-password)"
                    ),
                };
            }
            match flock_protocol::pake::server_reg_start(&core.oprf, &m1_b64, &user) {
                Ok(m2_b64) => AdminResponse::WebPwM2 { m2_b64 },
                Err(e) => AdminResponse::Err {
                    msg: format!("OPAQUE reg_start: {e}"),
                },
            }
        }
        AdminRequest::WebPwCommit {
            user,
            token,
            record_b64,
            profile,
            admin,
        } => match web_pw_commit(core, &user, token, &record_b64, profile, admin).await {
            Ok(()) => AdminResponse::WebPwDone { username: user },
            Err(e) => AdminResponse::Err { msg: e },
        },
        #[cfg(feature = "multi-primary")]
        AdminRequest::SignedWrite { req } => {
            use crate::netstate::NetError;
            match core.net.write_sync(req).await {
                Ok(resp) => AdminResponse::WriteReceipt {
                    text: format!("{resp:?}"),
                },
                Err(NetError::InvalidState(m)) if m.starts_with("sync:") => {
                    // SyncError strings (NoLeader/ForwardToLeader etc.) —— kept verbatim.
                    AdminResponse::Err { msg: m }
                }
                Err(e) => AdminResponse::Err { msg: e.to_string() },
            }
        }
    }
}

/// Runtime status snapshot (the observation surface of the M5 assertions: A6
/// epoch advance / A7 leader arbitration / A14 FRWD and source-VIP violation
/// counters / A15 locate redirect counter).
async fn stats_lines(core: &ServerCore) -> Vec<String> {
    let mut lines = Vec::new();
    lines.push(format!("epoch={}", core.net.epoch().await));
    lines.push(format!("sessions_online={}", core.sessions.device_count()));
    lines.push(format!("tun_vip={}", core.cfg.vip));
    // Review items 9/10: nonce overflow-reject counter + source VIP mismatch
    // (global cumulative and per-session limit-hit chain breaks).
    lines.push(format!(
        "nonce_overflow_rejects={}",
        core.guard.nonces.overflow_rejects()
    ));
    lines.push(format!(
        "src_vip_mismatches={}",
        crate::dataplane::src_vip_mismatches()
    ));
    lines.push(format!(
        "src_vip_mismatch_kills={}",
        crate::dataplane::src_vip_mismatch_kills()
    ));
    // Review item 11: Frp relay health events (unhealthy/recovered ——
    // non-zero is meaningful after starting in Frp mode; always 0 in Direct
    // mode).
    let (unhealthy, recovered) = crate::frp::relay_health_events();
    lines.push(format!("frp_relay_unhealthy_events={unhealthy}"));
    lines.push(format!("frp_relay_recovered={recovered}"));
    // Review item 7: cumulative inbound connections politely closed at the
    // concurrency cap + the configured cap.
    lines.push(format!(
        "sessions_overlimit={}",
        crate::server::sessions_overlimit()
    ));
    lines.push(format!("max_sessions={}", core.cfg.max_sessions));
    #[cfg(feature = "multi-primary")]
    if let Some(node) = &core.sync {
        lines.push(format!("node_id={}", node.id()));
        let leader = node
            .current_leader()
            .await
            .map(|l| l.to_string())
            .unwrap_or_default();
        lines.push(format!("leader={leader}"));
        lines.push(format!("breaker_open={}", node.breaker_open()));
        let f = node.forward().stats();
        lines.push(format!("fwd_forwarded={}", f.forwarded));
        lines.push(format!("fwd_delivered_local={}", f.delivered_local));
        lines.push(format!("fwd_delivered_kernel={}", f.delivered_kernel));
        lines.push(format!("fwd_outbound_kernel={}", f.outbound_kernel));
        lines.push(format!("fwd_not_here={}", f.not_here));
        lines.push(format!("fwd_locate_redirected={}", f.locate_redirected));
        lines.push(format!("fwd_dropped={}", f.dropped));
        lines.push(format!("fwd_icmp_unreachable={}", f.icmp_unreachable));
        lines.push(format!("fwd_src_violations={}", f.src_violations));
        lines.push(format!(
            "fwd_src_mismatch_rejected={}",
            f.src_mismatch_rejected
        ));
        lines.push(format!("fwd_hop_dropped={}", f.hop_dropped));
        lines.push(format!("lease_entries={}", node.lease().live_len()));
        let (d_ok, d_err, r_ok, r_err) = node.interconnect_diag();
        lines.push(format!(
            "ic_dial_ok={d_ok} ic_dial_err={d_err} ic_rpc_ok={r_ok} ic_rpc_err={r_err}"
        ));
        let d = node.dir().stats();
        lines.push(format!("dir_cache_hits={}", d.cache_hits));
        lines.push(format!("dir_linearizable_reads={}", d.linearizable_reads));
        lines.push(format!(
            "rejected_handshakes={}",
            node.rejected_handshakes()
        ));
    }
    lines
}

/// M8: the commit half of `web-admin-add` (shared by the admin endpoint and
/// the CLI fallback of "server not running ⇒ single-server direct write" ——
/// the single source of truth for the semantics).
///
/// Steps (§7-M8.3): target already has a password ⇒ reject with guidance;
/// user does not exist ⇒ CreateUser (UserExists ignored idempotently); token
/// mismatch (leftover from an earlier half-completed flow) ⇒ ResetPassword
/// overwrite (the record is empty anyway); SetPasswordBootstrap persists the
/// record + clears the token; `admin=true` ⇒ SetUserAdmin.
pub async fn web_pw_commit(
    core: &ServerCore,
    user: &str,
    token: [u8; 16],
    record_b64: &str,
    profile: u16,
    admin: bool,
) -> Result<(), String> {
    use crate::netstate::UserOpError;
    let map = |e: UserOpError| e.to_string();
    // Record canonicalization (decode validation) —— bad b64 never enters the
    // write path.
    let canonical = flock_protocol::pake::server_reg_canonical(record_b64)
        .map_err(|e| format!("record_b64: {e}"))?;
    match core.net.user_row(user).await {
        Some(row) if row.opaque_record.is_some() => {
            return Err(format!(
                "user {user} already has a password - web-admin-add is for first-time setup only; reset existing passwords via the Web UI (admin /api/users/{user}/reset-password)"
            ));
        }
        None => {
            // Create the account (carrying the token); already exists
            // (concurrent/retry) ⇒ ignored idempotently (token aligned below).
            match core.net.create_user(user, token).await {
                Ok(()) | Err(UserOpError::UserExists) => {}
                Err(e) => return Err(map(e)),
            }
        }
        Some(_) => {}
    }
    // Token alignment (an old token left over from a half-completed flow ⇒
    // overwrite; record empty ⇒ ResetPassword is lossless).
    if !core
        .net
        .user_row(user)
        .await
        .is_some_and(|r| r.pw_bootstrap == Some(token))
    {
        core.net.reset_password(user, token).await.map_err(map)?;
    }
    core.net
        .set_password_bootstrap(user, token, &canonical, profile)
        .await
        .map_err(map)?;
    if admin {
        core.net.set_user_admin(user, true).await.map_err(map)?;
    }
    Ok(())
}

/// Admin client (for CLI subcommands; one connection per request).
pub async fn client(
    addr: std::net::SocketAddr,
    req: AdminRequest,
) -> Result<AdminResponse, String> {
    let mut io = TcpStream::connect(addr).await.map_err(|e| e.to_string())?;
    send_msg(&mut io, &req).await.map_err(|e| e.to_string())?;
    let resp: AdminResponse = recv_msg(&mut io).await.map_err(|e| e.to_string())?;
    Ok(resp)
}
